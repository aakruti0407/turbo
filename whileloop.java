package com.basic;

import java.util.Scanner;

public class whileloop {
	public static void main(String[] args) {
		int n;
		Scanner sc=new  Scanner(System.in);
		System.out.println("Enter N :");
		n=sc.nextInt();
		while(n>0)
		{
			System.out.println("Tops Technologies");
			n--;
		}
	}

}
